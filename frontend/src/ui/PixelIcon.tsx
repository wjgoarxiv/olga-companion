function runs(rows: readonly string[]): readonly { x: number; y: number; w: number }[] {
  const width = Math.max(...rows.map((row) => row.length));
  const padLeft = Math.floor((12 - width) / 2);
  const padTop = Math.floor((12 - rows.length) / 2);
  const out: { x: number; y: number; w: number }[] = [];
  rows.forEach((row, index) => {
    let x = 0;
    while (x < row.length) {
      if (row[x] !== '#') { x += 1; continue; }
      let w = 1;
      while (x + w < row.length && row[x + w] === '#') w += 1;
      out.push({ x: x + padLeft, y: index + padTop, w });
      x += w;
    }
  });
  return out;
}

const SHAPES = Object.fromEntries(
  (Object.keys(ART) as PixelIconName[]).map((name) => [name, runs(ART[name])]),
) as Record<PixelIconName, readonly { x: number; y: number; w: number }[]>;

export const PIXEL_ICON_NAMES = Object.keys(ART) as readonly PixelIconName[];

export function PixelIcon({
  name,
  size = 24,
  label,
  className,
}: {
  readonly name: PixelIconName;
  /** Pixel size at 100 % UI scale; 24 is two device pixels per cell. */
  readonly size?: number;
  readonly label?: string;
  readonly className?: string;
}) {
  return (
    <svg
      className={className ? `px-icon ${className}` : 'px-icon'}
      viewBox="0 0 12 12"
      style={{ '--px': size } as CSSProperties}
      fill="currentColor"
      shapeRendering="crispEdges"
      aria-hidden={label === undefined ? true : undefined}
      role={label === undefined ? undefined : 'img'}
      aria-label={label}
      focusable="false"
    >
      {SHAPES[name].map((rect) => (
        <rect key={`${rect.x}-${rect.y}`} x={rect.x} y={rect.y} width={rect.w} height={1} />
      ))}
    </svg>
  );
}

/** The same symbol drawn inside an SVG (topology nodes): a nested viewport so
    the rects keep their 12x12 grid at any size. */
export function PixelIconInSvg({ name, x, y, size, className }: {
  readonly name: PixelIconName;
  readonly x: number;
  readonly y: number;
  readonly size: number;
  readonly className?: string;
}) {
  return (
    <svg
      className={className}
      x={x}
      y={y}
      width={size}
      height={size}
      viewBox="0 0 12 12"
      fill="currentColor"
      shapeRendering="crispEdges"
      aria-hidden="true"
    >
      {SHAPES[name].map((rect) => (
        <rect key={`${rect.x}-${rect.y}`} x={rect.x} y={rect.y} width={rect.w} height={1} />
      ))}
    </svg>
  );
}
